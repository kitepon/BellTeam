// Match only fixed semantic prefixes; never copy a free message, field value or stack to the wire.
export function normalizeMembersError(error) {
  const prefix = typeof error?.message === 'string' ? error.message.split(':', 1)[0] : ''
  const code = statuses.has(error?.code) ? error.code : statuses.has(prefix) ? prefix : null
  if (code === null) return error
  error.code = code
  error.status = statuses.get(code)
  return error
}

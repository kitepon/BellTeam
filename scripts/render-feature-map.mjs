import { readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

export function renderFeatureMap(modules) {
  const entries = Object.entries(modules).sort(([a], [b]) => a.localeCompare(b))
  const node = key => `m_${key.replaceAll('-', '_')}`
  const edges = entries.flatMap(([from, module]) => module.uses.map(use => {
    if (!modules[use.module]?.provides.includes(use.port)) throw new Error(`Unknown connection: ${from} -> ${use.module}:${use.port}`)
    return { from, to: use.module, port: use.port }
  }))
  const graph = selected => {
    const keys = new Set(selected.flatMap(edge => [edge.from, edge.to]))
    return ['```mermaid', 'flowchart LR', ...entries.filter(([key]) => keys.has(key)).map(([key, value]) =>
      `  ${node(key)}[${JSON.stringify(`${value.title} / ${value.owner}`)}]`), ...selected.map(edge =>
      `  ${node(edge.from)} -->|${JSON.stringify(edge.port)}| ${node(edge.to)}`), '```'].join('\n')
  }
  return [
    '# BellTeamの全体機能図', '',
    '<!-- Generated by scripts/render-feature-map.mjs. Edit modules/*/module.json instead. -->', '',
    '各機能の接続情報から生成する。個別の内部図と公開契約は下表の正本を参照。[担当と変更手順](module-ownership.md)。', '',
    '担当は設定済み。コード・詳細図の単独更新に向けた分離は各担当が実施中で、完了を意味しない。接続線は公開窓口への依存を示し、全てが直接の関数呼出しという意味ではない。', '',
    '## 本体の接続', '', graph(edges.filter(edge => !modules[edge.from].external && !modules[edge.to].external)), '',
    '## アプリ・独立製品との接続', '', graph(edges.filter(edge => modules[edge.from].external || modules[edge.to].external)), '',
    '## 担当図と公開窓口', '', '| 機能の正本 | 担当 | 公開窓口 |', '| --- | --- | --- |',
    ...entries.map(([key, value]) => `| [${value.title}](modules/${key}/README.md) | ${value.owner} | ${value.provides.join(' / ')} |`), '',
    '変更前に担当図と接続先の図を読み、図の変更要否と作業範囲を確認する。個別図・接続の変更後は `node scripts/render-feature-map.mjs` で再生成する。', '',
    '[旧全体図（2026-11-01の履歴）](feature-map-legacy-20261101.md)。外部製品内部の図は各製品の正本へ接続する。', '',
  ].join('\n')
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'docs', 'architecture')
  const entries = await readdir(join(root, 'modules'), { withFileTypes: true })
  const modules = Object.fromEntries(await Promise.all(entries.filter(entry => entry.isDirectory()).map(async entry =>
    [entry.name, JSON.parse(await readFile(join(root, 'modules', entry.name, 'module.json'), 'utf8'))])))
  await writeFile(join(root, 'feature-map.md'), renderFeatureMap(modules))
}
